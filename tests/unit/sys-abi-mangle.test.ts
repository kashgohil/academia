const BUILTINS = ["void", "bool", "char", "int", "unsigned", "long", "unsigned long", "long long", "float", "double"];
function parse(s: string): CType {
  const m = /^([PROK])\((.*)\)$/.exec(s);
  if (m) { const inner = parse(m[2]!); return m[1] === "P" ? ptrT(inner) : m[1] === "R" ? refT(inner) : m[1] === "O" ? rrefT(inner) : constT(inner); }
  if (/^T\d$/.test(s)) return tp(Number(s[1]));
  if (BUILTINS.includes(s)) return b(s as Builtin);
  return cls(...s.split("::"));
}
const list = (s: string) => (s ? s.split(";").map(parse) : []);
function decl(row: string): { d: FnDecl; itanium: string; msvc: string } {
  const [ns, c, name, params, k, targs, ret, itanium, msvc] = row.split("|");
  const d: FnDecl = { ns: ns ? ns.split("::") : [], name: name!, params: list(params!) };
  if (c) d.cls = c;
  if (k === "1") d.constMethod = true;
  if (targs) { d.targs = list(targs); d.ret = parse(ret!); }
  return { d, itanium: itanium!, msvc: msvc! };
}

